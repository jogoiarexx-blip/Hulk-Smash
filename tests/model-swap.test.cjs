'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.join(__dirname,'..');
const get=name=>fs.readFileSync(path.join(root,name),'utf8');
const glb=fs.readFileSync(path.join(root,'assets/models/hulk.glb'));
const checksum=crypto.createHash('sha256').update(glb).digest('hex');
assert.equal(checksum,'a1aac44ba93467ec4a6367ea2938265ff5033a2cf8e6f4d1a7c260235fe03f02', 'GLB must match user-supplied Hulk');
assert.equal(glb.toString('utf8',0,4),'glTF');
assert.equal(glb.readUInt32LE(8),glb.length);
const j=JSON.parse(glb.toString('utf8',20,20+glb.readUInt32LE(12)));
assert.equal(j.skins[0].joints.length,108);
assert.equal(j.animations.length,2);
const html=get('index.html'),game=get('src/game.js'),avatar=get('src/avatar.js');
for(const id of ['avatarPanel','avatarLive','avatarDetail','avatarRetry','avatarCompare','avatarFlip','avatarStatus'])
 assert.match(html,new RegExp(`id="${id}"`),`Missing diagnostic UI ${id}`);
assert.match(game,/avatarState='error'/);
assert.match(game,/if\(\$\('startButton'\)\)\{/);
assert.match(game,/\$\('startButton'\)\.disabled=kind==='loading'/);
assert.match(game,/reloadAvatar\(\)/);
assert.match(game,/newAvatar\.showModel\(!newAvatar\.visible\)/);
assert.match(game,/onStatus:\(stage,data\)=>/);
assert.match(game,/avatarError=String\(updateError\?/);
assert.match(game,/window\.__HULK_DIAGNOSTICS/);
assert.match(avatar,/fetch\(fullUrl\.href,\{cache:'no-store'\}\)/);
assert.match(avatar,/view\.getUint32\(0,true\)/);
assert.match(avatar,/parseAsync\(raw,new URL/);
assert.match(avatar,/const baseRot=/);
assert.match(avatar,/adapter\.showModel\(true\)/);
assert.match(avatar,/onStatus\('ready',adapter\)/);
assert.match(avatar,/legacyParts\.forEach\(p=>p\.visible=!this\.visible\)/);
assert.match(get('JOGAR-WINDOWS.bat'),/127\.0\.0\.1:8784/);
console.log(`v1.5.2: GLB original SHA-256 ${checksum}, 108 joints, 2 animations, checked loader, diagnostics, retry & controls: OK`);
